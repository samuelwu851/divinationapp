def _series(terms, t):
    return sum(a * math.cos(b + c * t) for a, b, c in terms)


def apparent_solar_longitude(jde: float) -> float:
    """太阳视黄经（度）：VSOP87D 地心真黄经 + 章动 + 光行差。"""
    t = (jde - 2451545.0) / 365250
    L = (_series(_L0, t) + _series(_L1, t) * t + _series(_L2, t) * t ** 2 + _series(_L3, t) * t ** 3
         + _series(_L4, t) * t ** 4 + _series(_L5, t) * t ** 5) * 1e-8
    R = (_series(_R0, t) + _series(_R1, t) * t) * 1e-8
    theta = math.degrees(L) + 180
    T = t * 10
    omega = math.radians(125.04452 - 1934.136261 * T)
    Lsun = math.radians(280.4665 + 36000.7698 * T)
    Lmoon = math.radians(218.3165 + 481267.8813 * T)
    dpsi = (-17.20 * math.sin(omega) - 1.32 * math.sin(2 * Lsun)
            - 0.23 * math.sin(2 * Lmoon) + 0.21 * math.sin(2 * omega)) / 3600
    aberration = -20.4898 / 3600 / R
    return (theta - 0.09033 / 3600 + dpsi + aberration) % 360


def solar_term_utc(year: int, name: str) -> datetime:
    """公历 year 年内某节气的 UTC 时刻（Newton 迭代逼近目标黄经）。"""
    target = JIEQI_LON[name]
    approx_doy = target / 360 * 365.2422 + 79.5
    if approx_doy > 365:
        approx_doy -= 365.2422
    jd = _jd(datetime(year, 1, 1, tzinfo=timezone.utc)) + approx_doy
    for _ in range(50):
        dt_days = delta_t_seconds(year) / 86400
        lam = apparent_solar_longitude(jd + dt_days)
        diff = (lam - target + 180) % 360 - 180
        if abs(diff) < 1e-7:
            break
        jd -= diff / 0.9856473
    return _from_jd(jd)


def solar_term_local(year: int, name: str, tz_hours: float = 8) -> datetime:
    return solar_term_utc(year, name).astimezone(timezone(timedelta(hours=tz_hours)))
